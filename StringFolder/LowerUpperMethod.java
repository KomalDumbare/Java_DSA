package StringFolder;

public class LowerUpperMethod {
    public static void main(String[] args)
    {
        // lower case
        String s1 = "HELLO";
        System.out.println("Original String: "+s1);
        String ans = s1.toLowerCase();
        System.out.println("Lowercase String: "+ans);

        //lowercase
        String s2 = "hello";
        System.out.println("Original String: "+s2);
        String an = s2.toUpperCase();
        System.out.println("Uppercase String: "+an);
    }
    
}
